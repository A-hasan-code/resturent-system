# Generates a LOCAL-DEV Pixalbotics Root CA + Authenticode code-signing certificate.
# Trusts the CA on THIS machine only. Does NOT satisfy Smart App Control on customer PCs
# (those need a public Microsoft Trusted Root CA - see docs\CODE-SIGNING.md).
#
#   powershell -ExecutionPolicy Bypass -File .\New-LocalDevCerts.ps1
#   powershell -ExecutionPolicy Bypass -File .\New-LocalDevCerts.ps1 -InstallTrust   # Admin once
#   .\Sign.ps1 -Path ..\..\releases\v1.3.0\HotelSystem-Setup-1.3.0.exe -Required
#
param(
  [switch]$InstallTrust,
  [string]$Company = "Pixalbotics",
  [string]$Password = ""
)

$ErrorActionPreference = "Stop"
$OpenSsl = @(
  "C:\Program Files\Git\usr\bin\openssl.exe",
  "${env:ProgramFiles}\OpenSSL-Win64\bin\openssl.exe",
  (Get-Command openssl -ErrorAction SilentlyContinue | Select-Object -ExpandProperty Source)
) | Where-Object { $_ -and (Test-Path $_) } | Select-Object -First 1

if (-not $OpenSsl) { throw "openssl.exe not found. Install Git for Windows or OpenSSL." }

function Invoke-OpenSsl([string[]]$argv) {
  $prev = $ErrorActionPreference
  $ErrorActionPreference = "Continue"
  try {
    & $OpenSsl @argv 2>&1 | ForEach-Object {
      if ($_ -is [System.Management.Automation.ErrorRecord]) {
        $t = $_.ToString()
        if ($t -match '^\.+|\+{3,}|^-{3,}$|Certificate request|subject=') { return }
        Write-Host $t
      } else {
        Write-Host $_
      }
    }
    if ($LASTEXITCODE -ne 0) { throw "openssl $($argv[0]) failed (exit $LASTEXITCODE)" }
  } finally {
    $ErrorActionPreference = $prev
  }
}

$Here = $PSScriptRoot
$CertDir = Join-Path $Here "certs"
New-Item -ItemType Directory -Force -Path $CertDir | Out-Null

$caKey = Join-Path $CertDir "Pixalbotics-RootCA.key"
$caCrt = Join-Path $CertDir "Pixalbotics-RootCA.crt"
$codeKey = Join-Path $CertDir "Pixalbotics-CodeSign.key"
$codeCsr = Join-Path $CertDir "Pixalbotics-CodeSign.csr"
$codeCrt = Join-Path $CertDir "Pixalbotics-CodeSign.crt"
$codePfx = Join-Path $CertDir "Pixalbotics-CodeSign.pfx"
$extFile = Join-Path $CertDir "codesign.ext"
$passFile = Join-Path $CertDir "pfx.password.txt"

if (-not $Password) {
  if (Test-Path $passFile) {
    $Password = (Get-Content $passFile -Raw).Trim()
  } else {
    $chars = [char[]]"ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789!@#"
    $bytes = New-Object byte[] 20
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $Password = -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
  }
}

Write-Host "Using OpenSSL: $OpenSsl" -ForegroundColor Cyan
Write-Host "Output: $CertDir" -ForegroundColor Cyan

$needGenerate = -not ((Test-Path $caCrt) -and (Test-Path $codePfx) -and (Test-Path $passFile))

if ($needGenerate) {
  if (-not (Test-Path $caCrt) -or -not (Test-Path $caKey)) {
    Write-Host "==> Generating $Company Root CA..."
    Invoke-OpenSsl @(
      "req", "-x509", "-newkey", "rsa:4096", "-sha256", "-days", "3650", "-nodes",
      "-keyout", $caKey, "-out", $caCrt,
      "-subj", "/C=PK/O=$Company/OU=Software/CN=$Company Root CA (Local Dev)"
    )
  } else {
    Write-Host "Root CA already exists - reusing." -ForegroundColor DarkYellow
  }

  @(
    "basicConstraints=CA:FALSE"
    "keyUsage=digitalSignature"
    "extendedKeyUsage=codeSigning"
    "subjectKeyIdentifier=hash"
    "authorityKeyIdentifier=keyid,issuer"
  ) | Set-Content -Path $extFile -Encoding ascii

  Write-Host "==> Generating $Company code-signing certificate..."
  Invoke-OpenSsl @(
    "req", "-newkey", "rsa:3072", "-sha256", "-nodes",
    "-keyout", $codeKey, "-out", $codeCsr,
    "-subj", "/C=PK/O=$Company/OU=Hotel System/CN=$Company Software"
  )
  Invoke-OpenSsl @(
    "x509", "-req", "-in", $codeCsr, "-CA", $caCrt, "-CAkey", $caKey, "-CAcreateserial",
    "-out", $codeCrt, "-days", "1095", "-sha256", "-extfile", $extFile
  )

  Write-Host "==> Exporting PFX..."
  $env:PFX_PASS = $Password
  Invoke-OpenSsl @(
    "pkcs12", "-export", "-out", $codePfx, "-inkey", $codeKey, "-in", $codeCrt, "-certfile", $caCrt,
    "-name", "$Company Hotel System Code Signing", "-passout", "env:PFX_PASS"
  )
  Remove-Item Env:PFX_PASS -ErrorAction SilentlyContinue
  Set-Content -Path $passFile -Value $Password -Encoding ascii -NoNewline
} else {
  Write-Host "Certs already present - skipping generation." -ForegroundColor DarkYellow
  $Password = (Get-Content $passFile -Raw).Trim()
}

$signingEnv = Join-Path $Here "signing.env"
$signToolPath = "C:\Program Files (x86)\Windows Kits\10\bin\10.0.18362.0\x64\signtool.exe"
@(
  "# LOCAL DEV ONLY - generated by New-LocalDevCerts.ps1 for $Company"
  "# Do not distribute this PFX. Customer PCs need a public Authenticode cert (CODE-SIGNING.md)."
  "HOTEL_SIGNTOOL=$signToolPath"
  "HOTEL_SIGN_PFX=$codePfx"
  "HOTEL_SIGN_PFX_PASSWORD=$Password"
  "HOTEL_SIGN_TIMESTAMP_URL=none"
  "HOTEL_SIGN_REQUIRED=1"
  "CSC_LINK=$codePfx"
  "CSC_KEY_PASSWORD=$Password"
) | Set-Content -Path $signingEnv -Encoding ascii

Write-Host ""
Write-Host "Ready:" -ForegroundColor Green
Write-Host "  CA:     $caCrt"
Write-Host "  PFX:    $codePfx"
Write-Host "  Config: $signingEnv"

if ($InstallTrust) {
  Write-Host ""
  Write-Host "==> Installing CA into LocalMachine\Root (requires Admin)..." -ForegroundColor Cyan
  $isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).
    IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
  if (-not $isAdmin) { throw "Run elevated: powershell -ExecutionPolicy Bypass -File .\New-LocalDevCerts.ps1 -InstallTrust" }

  Import-Certificate -FilePath $caCrt -CertStoreLocation Cert:\LocalMachine\Root | Out-Null
  $secure = ConvertTo-SecureString -String $Password -AsPlainText -Force
  Import-PfxCertificate -FilePath $codePfx -CertStoreLocation Cert:\LocalMachine\My -Password $secure -Exportable | Out-Null
  Import-PfxCertificate -FilePath $codePfx -CertStoreLocation Cert:\CurrentUser\My -Password $secure -Exportable | Out-Null
  Write-Host "CA trusted on this PC. Code-sign cert imported to Personal store." -ForegroundColor Green
} else {
  Write-Host ""
  Write-Host "Next (once, as Administrator):" -ForegroundColor Yellow
  Write-Host "  powershell -ExecutionPolicy Bypass -File `"$PSCommandPath`" -InstallTrust"
  Write-Host "Then sign:"
  Write-Host "  .\Sign.ps1 -Path ..\..\releases\v1.3.0\HotelSystem-Setup-1.3.0.exe -Required"
}

Write-Host ""
Write-Host "NOTE: LOCAL DEV trust only. Other PCs / Smart App Control still need a public CA cert." -ForegroundColor Yellow
